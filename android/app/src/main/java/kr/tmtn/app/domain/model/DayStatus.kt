package kr.tmtn.app.domain.model

/**
 * 기록 달력의 하루 상태.
 *
 * **쉼과 미완료를 반드시 구분한다.**
 * 쉼은 사용자가 직접 고른 것이고, 미완료는 그냥 지나간 날이다.
 * 둘을 같게 보이면 "내가 쉬기로 한 날" 과 "빠뜨린 날" 이 뒤섞인다.
 *
 * 화면 표시는 `TmtnCalendar` 규격을 따른다 —
 * 실천은 꽉 찬 원, 쉼은 **실선** 테두리, 미완료는 **점선** 테두리.
 * 색만이 아니라 선 종류로도 갈라 두어야 색을 구별하기 어려운 사람도 읽는다.
 */
enum class DayStatus {
    /** 미션을 끝낸 날 */
    DONE,

    /** 사용자가 직접 "오늘은 쉬어가기" 를 누른 날. 연속 기록이 끊기지 않는다 */
    REST,

    /** 아무것도 하지 않고 지나간 날. 여기서 연속 기록이 끊긴다 */
    MISSED,

    /** 아직 오지 않은 날 */
    FUTURE,
}

/** 한 주에 쉴 수 있는 횟수. 서버가 생기면 서버가 세야 기기를 바꿔도 맞는다. */
const val REST_PER_WEEK = 2
